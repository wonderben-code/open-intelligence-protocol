/**
 * Generates, from the schemas in `src/`:
 *
 *   - `spec/schemas/*.json`, the JSON Schemas (2020-12) for implementers;
 *   - `src/generated/validators.ts`, validators compiled ahead of time by Ajv,
 *     so that the package never builds code at run time and works where
 *     `eval` is forbidden (browsers with a strict CSP, edge runtimes).
 *
 * With `--check` it writes nothing and fails if any file is out of date.
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { Ajv2020 } from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";

import { type JsonSchema, jsonSchemas } from "../src/json-schemas.ts";
import { Defs } from "../src/naming.ts";
import { DEFINING_CLAUSE, isRecordType, recordSchemas, sharedSchemas } from "../src/registry.ts";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(packageRoot, "..", "..");
const schemaDir = join(repoRoot, "spec", "schemas");
const validatorsFile = join(packageRoot, "src", "generated", "validators.ts");

const HEADER = "Generated by packages/schema/scripts/generate.ts. Do not edit; run `pnpm schemas`.";

function schemaFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const [name, schema] of Object.entries(jsonSchemas)) {
    files.set(join(schemaDir, `${name}.json`), `${JSON.stringify(schema, null, 2)}\n`);
  }
  const rows = Object.entries(jsonSchemas).map(([name, schema]) => {
    const clause = isRecordType(name) ? DEFINING_CLAUSE[name] : "";
    return `| [\`${name}\`](${name}.json) | \`${String(schema["$id"])}\` | ${clause} | ${String(schema["description"])} |`;
  });
  files.set(
    join(schemaDir, "README.md"),
    [
      "# OIP JSON Schemas",
      "",
      `<!-- ${HEADER} -->`,
      "",
      "These are JSON Schemas (draft 2020-12) for every record type of [core Section 11](../core.md#11-record-types), generated from [`@oip/schema`](../../packages/schema). They are a convenience for implementers. The specifications are normative; if a schema and a specification disagree, the specification wins and the schema is fixed.",
      "",
      "The schemas refer to each other by `$id` (`urn:oip:schema:<name>`), so load them all into one registry. `Record.json` dispatches on `type`.",
      "",
      "A schema says whether a value is a well-formed record. It does not verify anything:",
      "",
      "- A few structural rules cannot be written in JSON Schema, and `@oip/schema` checks them in code. Examples: a delegation's delegate differs from its author (Layer 1, 11.1); thresholds are majorities (Layer 1, 3.4); each party to a Commitment appears once (Layer 2, 5.1); policy statements nest at most 8 deep (Layer 1, 11.3).",
      "- A record's `proof` members are objects here. Each proof is checked against `Proof.json` when it is verified, because a malformed proof never counts but does not make its record malformed (core 5.5).",
      "- Signatures, identity logs, delegation chains and every rule about time are checked by verification, not by a schema.",
      "",
      "Unknown members are allowed in records, because readers preserve and ignore them (core 1.7). Proofs, controllers and key entries are closed.",
      "",
      "| Schema | `$id` | Defined in | Description |",
      "|---|---|---|---|",
      ...rows,
      "",
    ].join("\n"),
  );
  return files;
}

function validatorsSource(): string {
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    strict: true,
    // Conditional subschemas (`if`, `not`, `contains`) constrain members without
    // restating their `type` or their definition.
    strictTypes: false,
    strictRequired: false,
    // Stop at the first error: collecting every error from hostile input is a denial-of-service risk.
    allErrors: false,
    // Compile each shared definition once and call it, instead of repeating it at every use.
    inlineRefs: false,
    unicodeRegExp: true,
    validateFormats: false,
  });
  // Ajv compiles a schema it knows by `$id` once, but a fragment of another
  // document once for every schema that refers to it. So register each shared
  // definition as a schema of its own rather than the `Defs` bundle.
  for (const definition of Object.values(Defs.$defs)) ajv.addSchema(definition);
  const compiled: Record<string, JsonSchema> = {};
  for (const name of Object.keys({ ...recordSchemas, ...sharedSchemas })) {
    const schema = jsonSchemas[name];
    if (schema === undefined) throw new Error(`no JSON Schema for ${name}`);
    ajv.addSchema(schema);
    compiled[name] = schema;
  }
  const exportsMap = Object.fromEntries(
    Object.entries(compiled).map(([name, schema]) => [name, String(schema["$id"])]),
  );
  // The module is CommonJS: its function is both `module.exports` and `exports.default`.
  let code = standalone.default(ajv, exportsMap);

  // Ajv emits CommonJS `require` calls for its two runtime helpers even in ESM
  // mode. Point them at our own implementations instead.
  code = code
    .replace(/^"use strict";\s*/, "")
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', "codePointLength")
    .replaceAll('require("ajv/dist/runtime/equal").default', "deepEqual");
  if (code.includes("require(")) {
    throw new Error("the generated validators still call require(); extend the rewrites above");
  }

  // Keep one typed export, so that the declaration file does not depend on Ajv's generated shapes.
  const names: string[] = [];
  code = code.replace(
    /^export const (\w+) = (\w+);$/gm,
    (_line: string, name: string, fn: string) => {
      names.push(`  ${name}: ${fn},`);
      return "";
    },
  );
  if (names.length !== Object.keys(compiled).length) {
    throw new Error("could not find every exported validator in Ajv's output");
  }

  // The two lines below are the generated file's header, not this file's.
  // REUSE-IgnoreStart
  const licence = [
    "// SPDX-FileCopyrightText: 2026 Ekram Alam and the Open Intelligence Protocol contributors",
    "// SPDX-License-Identifier: Apache-2.0",
  ];
  // REUSE-IgnoreEnd

  return [
    ...licence,
    "// @ts-nocheck",
    `// ${HEADER}`,
    "",
    'import { codePointLength, deepEqual } from "../runtime.ts";',
    "",
    "/** One error from a compiled validator. */",
    "export interface ValidatorError {",
    "  readonly instancePath: string;",
    "  readonly schemaPath: string;",
    "  readonly keyword: string;",
    "  readonly message?: string;",
    "}",
    "",
    "/** A validator compiled ahead of time. After a failed call, `errors` says why. */",
    "export interface CompiledValidator {",
    "  (data: unknown): boolean;",
    "  errors?: readonly ValidatorError[] | null;",
    "}",
    "",
    code.trim(),
    "",
    "export const validators: Readonly<Record<string, CompiledValidator>> = {",
    ...names,
    "};",
    "",
  ].join("\n");
}

const expected = schemaFiles();
expected.set(validatorsFile, validatorsSource());

const stale: string[] = [];
for (const [file, content] of expected) {
  let current: string | undefined;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = undefined;
  }
  if (current !== content) stale.push(file);
}
// A schema that no longer exists must not linger in spec/schemas/.
const orphans = readdirSync(schemaDir, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => join(schemaDir, entry.name))
  .filter((file) => !expected.has(file));

if (process.argv.includes("--check")) {
  const problems = [...stale, ...orphans].map((file) => relative(repoRoot, file));
  if (problems.length > 0) {
    console.error(
      `Out of date: ${problems.join(", ")}\nRun \`pnpm schemas\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`${expected.size} generated files are current.`);
} else {
  for (const file of stale) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, expected.get(file) ?? "");
  }
  for (const file of orphans) rmSync(file);
  console.log(
    `${expected.size} generated files; wrote ${stale.length}, removed ${orphans.length}.`,
  );
}

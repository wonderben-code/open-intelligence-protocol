import { existsSync } from "node:fs";

import { defineConfig } from "vitest/config";

// Packages that must reach 95% line and branch coverage (BUILD.md, Section 2).
const VERIFICATION_PACKAGES = ["core", "identity", "delegation", "web", "net"];

// Files of `@oip/server` held to the same threshold.
const SERVER_GUARDS = ["auth", "http", "ip", "fetcher"];

const strict = { lines: 95, branches: 95, functions: 95, statements: 95 };

export default defineConfig({
  test: {
    // One project per workspace package that has tests.
    projects: ["{packages,apps,examples}/*/vitest.config.ts"],
    coverage: {
      provider: "v8",
      reporter: ["text-summary", "json-summary", "html"],
      include: ["**/src/**/*.ts"],
      exclude: [
        // Code generated by Ajv. The schema tests exercise it through `validateRecord`.
        "**/schema/src/generated/**",
        // Test helpers, not shipped.
        "**/testkit/**",
        // Build scripts, and the fixtures that break the layering rules on purpose.
        "**/scripts/**",
        // Mutation testing works on copies of the repository (stryker.config.mjs).
        ".stryker-tmp/**",
      ],
      thresholds: {
        // Each file must meet the threshold, so that an untested file cannot
        // hide behind well-tested ones.
        perFile: true,
        lines: 85,
        branches: 85,
        functions: 85,
        statements: 85,
        // A threshold for a package that does not exist yet would fail at 0%.
        ...Object.fromEntries(
          VERIFICATION_PACKAGES.filter((name) => existsSync(`packages/${name}`)).map((name) => [
            `**/packages/${name}/src/**/*.ts`,
            strict,
          ]),
        ),
        // The parts of the services' shared package that judge a request or guard what a
        // service connects to (ADR-0013).
        ...Object.fromEntries(
          SERVER_GUARDS.filter((name) => existsSync(`packages/server/src/${name}.ts`)).map(
            (name) => [`**/packages/server/src/${name}.ts`, strict],
          ),
        ),
      },
    },
  },
});
